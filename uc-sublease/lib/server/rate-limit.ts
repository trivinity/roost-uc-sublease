// Small per-user limiter kept in memory. On serverless each instance has its own counts, so this is a best-effort
// brake against a runaway page; the hard cap is the daily quota set on the Google API key.
const hits = new Map<string, number[]>();

export function allow(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  if (recent.length >= limit) {
    hits.set(key, recent);
    return false;
  }
  recent.push(now);
  hits.set(key, recent);
  return true;
}
