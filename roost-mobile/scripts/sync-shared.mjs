// Copies the shared app logic (data, filters, copy, formatting) and the demo photos from the web app,
// so the web and mobile apps always show the same listings and use the same wording.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..", "..", "uc-sublease");
const out = join(here, "..", "src", "lib");
mkdirSync(out, { recursive: true });

for (const f of ["types", "listings", "filters", "format", "copy", "insights", "config"]) {
  const src = readFileSync(join(web, "lib", `${f}.ts`), "utf8");
  writeFileSync(join(out, `${f}.ts`), `// AUTO-COPIED from uc-sublease/lib/${f}.ts by \`npm run sync\`. Edit the web version, not this file.\n${src}`);
}

const photos = join(here, "..", "assets", "photos");
mkdirSync(photos, { recursive: true });
const names = readdirSync(join(web, "public", "photos")).filter((n) => n.endsWith(".jpg"));
for (const n of names) copyFileSync(join(web, "public", "photos", n), join(photos, n));

// Metro needs static require() calls, so generate the photo lookup table too.
const lines = names.sort().map((n) => `  "/photos/${n}": require("../../assets/photos/${n}"),`);
writeFileSync(
  join(out, "photos.ts"),
  `// AUTO-GENERATED by \`npm run sync\`. Maps the photo paths used in listings to bundled images.\nimport type { ImageSourcePropType } from "react-native";\n\nconst PHOTOS: Record<string, ImageSourcePropType> = {\n${lines.join("\n")}\n};\n\nexport const photoSource = (path: string): ImageSourcePropType => PHOTOS[path] ?? PHOTOS["/photos/living-1.jpg"];\n`,
);
console.log(`synced ${names.length} photos and shared logic`);
